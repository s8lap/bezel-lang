#!/usr/bin/env python3
"""test_dup_scan.py -- find EXACT-duplicate gtest rows (#5233 Phase 1).

Stdlib-only.  Re-creation of the R25 scanner described in #5233's *Method*.

Two rows are an EXACT duplicate when, after C++ comments and layout whitespace
are removed, both of these are identical:

  * the PROGRAM  -- every string literal in the row's body, plus the string
                    literals of every file-level definition the body reaches;
  * the BODY     -- the whole `BEZEL_TEST(suite, name) { ... }` token stream
                    (assertions, exit codes, loop counts, needles, helper calls)
                    PLUS the text of every file-level helper/constant it reaches
                    (transitively).  Two files that both call `run(...)` but
                    define `run` differently are therefore NOT duplicates.

The definition of "exact" is deliberately NO LOOSER than #5233's:
  * rows that differ in any literal (an exit code, a loop count, a needle) are
    not duplicates;
  * adjacent string literals are concatenated (so `"a " "b"` equals `"a b"`)
    and whitespace BETWEEN C++ tokens is ignored, but the decoded CONTENT of a
    string literal is compared byte-exact: whitespace inside a literal is
    significant (it may sit inside a Bezel string literal, an expected stdout
    or a needle);
  * every file-level definition a row reaches is part of its key: each
    declarator of a multi-declarator statement (`const char* kA = ..., *kB =
    ...;`) is registered under its own name, and the identifiers inside a
    `#define` body are followed like any other definition's;
  * rows whose body, or a definition in their own file that they reach, names
    `__FILE__`, `__LINE__`, `__COUNTER__` or `__func__` are never reported
    (their behaviour may depend on where they sit).  The test headers'
    assertion macros use `__FILE__`/`__LINE__` only in failure messages, so
    an identifier reached only through a header does not count.

Known limits: a program built at run time by a helper or by `std::string`
concatenation is only seen through the literals it contains.  Test headers
(`#include "..."` resolving under tests/) ARE read, and a name the row's own
file does not define is looked up in them; system and src/ headers are not.
Rows generated by a row macro (a `#define` whose body expands to BEZEL_TEST,
e.g. `ROW(...)`, `REJECT_ROW(...)`) are never grouped (so never proposed for
deletion), but `--count-rows` counts them, so its totals match
BEZEL_TEST_ENUMERATE=1.

Usage:
  scripts/test_dup_scan.py                     human-readable groups on stdout
  scripts/test_dup_scan.py --json OUT.json     also write the groups as JSON
  scripts/test_dup_scan.py --exclude FILE...   treat these test files as
                                               excluded: a group is "outside the
                                               excluded set" only if NONE of its
                                               rows lives in an excluded file
  scripts/test_dup_scan.py --count-rows        print row counts per area (BEZEL_TEST
                                               rows plus row-macro invocations)
  scripts/test_dup_scan.py --selftest          run the scanner over
                                               scripts/testdata/test_dup_scan/ and
                                               check the exact expected groups
Exit status: 0 when no exact group lies outside the excluded set, 1 otherwise,
2 on a scanner error.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AREAS = {
    "codegen": ["codegen"],
    "ownership": ["ownership"],
    "sema": ["sema", "flow"],
    "frontend": ["lexer", "parser"],
    "module": ["module"],
    "support": ["runtime", "support"],
}
NONDETERMINISTIC = {"__FILE__", "__LINE__", "__COUNTER__", "__func__"}

ESC = {"n": "\n", "t": "\t", "r": "\r", "0": "\0", "\\": "\\", '"': '"',
       "'": "'", "a": "\a", "b": "\b", "f": "\f", "v": "\v", "?": "?"}


def decode_plain(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "x":
                m = re.match(r"[0-9a-fA-F]+", s[i + 2:])
                if m:
                    out.append(chr(int(m.group(0), 16) & 0x10FFFF))
                    i += 2 + len(m.group(0))
                    continue
            if n in "01234567":
                m = re.match(r"[0-7]{1,3}", s[i + 1:])
                out.append(chr(int(m.group(0), 8)))
                i += 1 + len(m.group(0))
                continue
            if n in ESC:
                out.append(ESC[n])
                i += 2
                continue
            out.append(c + n)  # unknown escape: keep verbatim
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


class Tok:
    __slots__ = ("kind", "text", "sub")

    def __init__(self, kind, text, sub=None):
        self.kind = kind  # id num str chr punct pp
        self.text = text
        self.sub = sub    # pp only: the directive's own tokens (after '#')

    def __repr__(self):
        return "%s:%r" % (self.kind, self.text)


NUM_RE = re.compile(r"(?:0[xX][0-9a-fA-F']+|0[bB][01']+|[0-9][0-9']*(?:\.[0-9']*)?(?:[eE][+-]?[0-9]+)?)[A-Za-z_]*|\.[0-9][0-9']*(?:[eE][+-]?[0-9]+)?[A-Za-z_]*")
ID_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
STR_PREFIX_RE = re.compile(r"(?:u8|u|U|L)?")
PUNCT3 = ("<<=", ">>=", "...", "->*", "<=>")
PUNCT2 = ("::", "->", "++", "--", "<<", ">>", "<=", ">=", "==", "!=", "&&", "||",
          "+=", "-=", "*=", "/=", "%=", "&=", "|=", "^=", ".*")


_MASTER = re.compile(
    r"""(?P<ws>[ \t\r\f\v\n]+)
    |(?P<lc>//[^\n]*)
    |(?P<bc>/\*.*?\*/)
    |(?P<raw>(?:u8|u|U|L)?R"(?P<delim>[^()\\ \t\n]{0,16})\()
    |(?P<str>(?:u8|u|U|L)?"(?:[^"\\\n]|\\.)*")
    |(?P<chr>(?:u8|u|U|L)?'(?:[^'\\\n]|\\.)+')
    |(?P<id>[A-Za-z_][A-Za-z0-9_]*)
    |(?P<num>(?:0[xX][0-9a-fA-F']+|0[bB][01']+|[0-9][0-9']*(?:\.[0-9']*)?(?:[eE][+-]?[0-9]+)?|\.[0-9][0-9']*(?:[eE][+-]?[0-9]+)?)[A-Za-z_]*)
    |(?P<p3><<=|>>=|\.\.\.|->\*|<=>)
    |(?P<p2>::|->|\+\+|--|<<|>>|<=|>=|==|!=|&&|\|\||\+=|-=|\*=|/=|%=|&=|\|=|\^=|\.\*)
    |(?P<p1>.)""", re.S | re.X)


def tokenize(src):
    """C++ tokens with comments dropped.  String tokens carry decoded content."""
    toks = []
    i = 0
    n = len(src)
    match = _MASTER.match
    at_line_start = True
    while i < n:
        if at_line_start:
            # preprocessor line?
            k = i
            while k < n and src[k] in " \t":
                k += 1
            if k < n and src[k] == "#":
                j = k
                while True:
                    e = src.find("\n", j)
                    if e < 0:
                        j = n
                        break
                    if src[e - 1] == "\\":
                        j = e + 1
                        continue
                    j = e
                    break
                line = src[k + 1:j].replace("\\\n", "")  # splice continuations
                sub = tokenize(line)
                text = re.sub(r"/\*.*?\*/", " ", src[k:j], flags=re.S)
                text = re.sub(r"//.*", "", text)
                toks.append(Tok("pp", " ".join(text.split()), sub))
                i = j
                at_line_start = False
                continue
            at_line_start = False
        m = match(src, i)
        kind = m.lastgroup
        if kind == "delim":
            kind = "raw"
        if kind == "ws":
            if "\n" in m.group(0):
                at_line_start = True
            i = m.end()
            continue
        if kind in ("lc", "bc"):
            if kind == "bc" and "\n" in m.group(0):
                at_line_start = False
            i = m.end()
            continue
        if kind == "raw":
            delim = m.group("delim")
            end = src.find(")" + delim + '"', m.end())
            if end < 0:
                raise ValueError("unterminated raw string")
            toks.append(Tok("str", src[m.end():end]))
            i = end + len(delim) + 2
            continue
        text = m.group(0)
        if kind == "str":
            q = text.index('"')
            toks.append(Tok("str", decode_plain(text[q + 1:-1])))
        elif kind == "chr":
            toks.append(Tok("chr", text))
        elif kind == "id":
            toks.append(Tok("id", text))
        elif kind == "num":
            toks.append(Tok("num", text))
        else:
            toks.append(Tok("punct", text))
        i = m.end()
    return toks


def merge_strings(toks):
    out = []
    for t in toks:
        if t.kind == "str" and out and out[-1].kind == "str":
            out[-1] = Tok("str", out[-1].text + t.text)
        else:
            out.append(t)
    return out


def flat(toks):
    """Tokens with every preprocessor directive replaced by its own tokens."""
    for t in toks:
        if t.kind == "pp":
            yield from flat(t.sub)
        else:
            yield t


def idents(toks):
    return [t.text for t in flat(toks) if t.kind == "id"]


def render(toks):
    """Canonical text of a token list (strings are escaped to one line).

    String CONTENT is kept byte-exact; only the C++ layout (whitespace between
    tokens, comments, how a literal is split into adjacent literals) is
    normalised away.  A directive renders as '#' plus its own tokens."""
    parts = []
    for t in merge_strings(toks):
        if t.kind == "str":
            parts.append("S" + json.dumps(t.text))
        elif t.kind == "pp":
            parts.append("#[" + render(t.sub) + "]")
        else:
            parts.append(t.text)
    return " ".join(parts)


def programs(toks):
    return [t.text for t in merge_strings(list(flat(toks))) if t.kind == "str"]


def match_brace(toks, i):
    """toks[i] is '{'; return the index of its matching '}'."""
    depth = 0
    for j in range(i, len(toks)):
        if toks[j].kind == "punct":
            if toks[j].text == "{":
                depth += 1
            elif toks[j].text == "}":
                depth -= 1
                if depth == 0:
                    return j
    raise ValueError("unbalanced braces")


class FileScan:
    def __init__(self, path):
        self.path = path
        with open(os.path.join(ROOT, path), encoding="utf-8", errors="replace") as f:
            toks = tokenize(f.read())
        self.tests = []   # (suite, name, body_toks)
        self.defs = defaultdict(list)  # name -> [token lists]
        self.includes = [m.group(1) for t in toks if t.kind == "pp"
                         for m in [re.match(r'#\s*include\s*"([^"]+)"', t.text)] if m]
        self.row_macros = set()  # macros of this file whose body expands to BEZEL_TEST
        for t in toks:
            if t.kind == "pp":
                m = re.match(r"#\s*define\s+([A-Za-z_]\w*)\(", t.text)
                if m and "BEZEL_TEST" in idents(t.sub):
                    self.row_macros.add(m.group(1))
        self.macro_rows = 0  # row-macro invocations at file scope
        self._split(toks)
        self.hdr_defs = None  # name -> token lists, from reachable headers

    def lookup(self, name):
        d = self.defs.get(name)
        if d:
            return d
        if self.hdr_defs is None:
            self.hdr_defs = header_defs(self.path)
        return self.hdr_defs.get(name, ())

    def _split(self, toks):
        i = 0
        n = len(toks)
        stmt = []
        while i < n:
            t = toks[i]
            if t.kind == "pp":
                i += 1
                m = re.match(r"#\s*define\s+([A-Za-z_]\w*)", t.text)
                if m:
                    self.defs[m.group(1)].append([t])
                continue
            if (t.kind == "id" and t.text == "BEZEL_TEST" and not stmt
                    and i + 1 < n and toks[i + 1].text == "("):
                j = i + 2
                depth = 1
                args = []
                cur = []
                while depth:
                    x = toks[j]
                    if x.text == "(" and x.kind == "punct":
                        depth += 1
                    elif x.text == ")" and x.kind == "punct":
                        depth -= 1
                        if depth == 0:
                            break
                    if depth == 1 and x.text == "," and x.kind == "punct":
                        args.append(cur)
                        cur = []
                    else:
                        cur.append(x)
                    j += 1
                args.append(cur)
                while toks[j].text != "{":
                    j += 1
                e = match_brace(toks, j)
                suite = "".join(a.text for a in args[0])
                name = "".join(a.text for a in args[1])
                self.tests.append((suite, name, toks[j:e + 1]))
                i = e + 1
                continue
            if (t.kind == "id" and t.text in self.row_macros and not stmt
                    and i + 1 < n and toks[i + 1].text == "("):
                # `ROW(name, ...)`: a generated row.  Counted, never grouped.
                depth = 0
                j = i + 1
                while True:
                    x = toks[j]
                    if x.kind == "punct" and x.text == "(":
                        depth += 1
                    elif x.kind == "punct" and x.text == ")":
                        depth -= 1
                        if depth == 0:
                            break
                    j += 1
                self.macro_rows += 1
                i = j + 1
                if i < n and toks[i].text == ";":
                    i += 1
                continue
            if t.kind == "punct" and t.text == "{":
                head = stmt
                e = match_brace(toks, i)
                is_ns = bool(head) and head[0].text in ("namespace", "extern")
                if is_ns:
                    stmt = []
                    # descend: namespace contents are scanned in place
                    self._split(toks[i + 1:e])
                    i = e + 1
                    continue
                # function body / struct body / brace-init: part of this stmt
                stmt = stmt + toks[i:e + 1]
                i = e + 1
                # a function / struct definition ends at the '}' (struct has ';')
                nxt = toks[i] if i < n else None
                is_func_like = any(x.text == "(" for x in head) and not any(
                    x.text == "=" for x in head)
                if nxt is not None and nxt.text == ";":
                    stmt.append(nxt)
                    i += 1
                    self._commit(stmt)
                    stmt = []
                elif is_func_like or (head and head[0].text in ("struct", "class", "enum", "union")):
                    self._commit(stmt)
                    stmt = []
                continue
            if t.kind == "punct" and t.text == ";":
                stmt.append(t)
                self._commit(stmt)
                stmt = []
                i += 1
                continue
            stmt.append(t)
            i += 1
        if stmt:
            self._commit(stmt)

    def _commit(self, stmt):
        if not stmt:
            return
        names = set()
        head = []
        for x in stmt:
            if x.kind == "punct" and x.text in ("{", "=", ";"):
                break
            head.append(x)
        for k, x in enumerate(head):
            if x.kind != "id":
                continue
            nxt = head[k + 1].text if k + 1 < len(head) else ""
            prev = head[k - 1].text if k else ""
            if nxt == "(" or k == len(head) - 1 or prev in ("struct", "class", "enum", "union", "using", "typedef"):
                names.add(x.text)
        if not names and head:
            for x in reversed(head):
                if x.kind == "id":
                    names.add(x.text)
                    break
        # Every LATER declarator of `const char* kA = "..", *kB = "..";` is a
        # definition too: split at depth-0 commas and register the last
        # identifier before the declarator's `=`, `(`, `[`, `{` or end.
        # Registering a name too many only makes keys more specific
        # (conservative); registering one too few makes false duplicates.
        depth = 0
        seg = None
        for x in stmt:
            if x.kind == "punct" and x.text in ("(", "[", "{"):
                depth += 1
            elif x.kind == "punct" and x.text in (")", "]", "}"):
                depth -= 1
            if depth == 0 and x.kind == "punct" and x.text == ",":
                if seg is not None:
                    self._declarator(seg, names)
                seg = []
                continue
            if seg is not None:
                seg.append(x)
        if seg is not None:
            self._declarator(seg, names)
        # `using bezel::test::runAot;` -> runAot ; `using A = B;` -> A
        for nm in names:
            self.defs[nm].append(stmt)

    @staticmethod
    def _declarator(seg, names):
        last = None
        for x in seg:
            if x.kind == "punct" and x.text in ("=", "(", "[", "{", ";"):
                break
            if x.kind == "id":
                last = x.text
        if last is not None:
            names.add(last)


_HDR_CACHE = {}


def _resolve_include(inc, from_path):
    for base in (os.path.dirname(from_path), "tests", "tests/support"):
        cand = os.path.normpath(os.path.join(base, inc))
        if cand.startswith("tests/") and os.path.isfile(os.path.join(ROOT, cand)):
            return cand
    return None  # system / src header: not a test helper, identical for every row


def _header(path):
    if path not in _HDR_CACHE:
        fs = FileScan(path)
        _HDR_CACHE[path] = fs
    return _HDR_CACHE[path]


def header_defs(path):
    """name -> definitions, over every test header reachable from `path`."""
    out = defaultdict(list)
    seen = set()
    work = [path]
    while work:
        cur = work.pop()
        fs = _header(cur) if cur != path else _top(cur)
        for inc in fs.includes:
            r = _resolve_include(inc, cur)
            if r is None or r in seen:
                continue
            seen.add(r)
            h = _header(r)
            for nm, ds in h.defs.items():
                out[nm].extend(ds)
            work.append(r)
    return out


_TOP = {}


def _top(path):
    return _TOP[path]


def closure(fs, body):
    """Texts of every file-level definition reachable from `body`."""
    seen = set()
    texts = []
    work = idents(body)
    allidents = set(work)
    while work:
        nm = work.pop()
        if nm in seen:
            continue
        seen.add(nm)
        local = nm in fs.defs
        for d in fs.lookup(nm):
            texts.append((nm, d))
            for nm2 in idents(d):  # follows identifiers inside #define bodies
                if nm2 not in seen:
                    work.append(nm2)
                    # A test header's assertion macros (BEZEL_EXPECT_*) use
                    # __FILE__/__LINE__ only in their failure messages; only
                    # the row's own file can make its behaviour position-bound.
                    if local:
                        allidents.add(nm2)
    return texts, allidents


def row_key(fs, body):
    texts, idents = closure(fs, body)
    if idents & NONDETERMINISTIC:
        return None
    ctext = sorted(set((nm, render(d)) for nm, d in texts))
    ctoks = [t for _, d in texts for t in flat(d)]
    prog = programs(body) + sorted(set(programs(ctoks)))
    body_text = render(body)
    h_prog = hashlib.sha256(json.dumps(prog).encode()).hexdigest()
    h_body = hashlib.sha256(json.dumps([body_text, ctext]).encode()).hexdigest()
    return h_prog, h_body, sum(len(p) for p in prog)


def test_files():
    out = []
    for areadirs in AREAS.values():
        for d in areadirs:
            p = os.path.join(ROOT, "tests", d)
            if not os.path.isdir(p):
                continue
            for f in sorted(os.listdir(p)):
                if f.endswith(".cpp"):
                    out.append("tests/%s/%s" % (d, f))
    for f in sorted(os.listdir(os.path.join(ROOT, "tests"))):
        if f.endswith(".cpp") and f != "test_main.cpp":
            out.append("tests/" + f)
    return out


def area_of(path):
    d = path.split("/")[1]
    for a, dirs in AREAS.items():
        if d in dirs:
            return a
    return "support"


def first_added(path):  # only used for files with no issue number in the name
    """Commit timestamp of the commit that added the file (oldest first)."""
    try:
        r = subprocess.run(
            ["git", "log", "--diff-filter=A", "--follow", "--format=%ct", "--", path],
            cwd=ROOT, capture_output=True, text=True, check=True)
        ts = [int(x) for x in r.stdout.split()]
        return min(ts) if ts else 1 << 60
    except Exception:
        return 1 << 60


def issue_num(path):
    """Lowest issue number in the file name, or None."""
    nums = [int(x) for x in re.findall(r"(?<![0-9])([0-9]{2,5})(?![0-9])", os.path.basename(path))]
    return min(nums) if nums else None


def keep_order_key(path, ts_cache):
    inum = issue_num(path)
    if inum is not None:
        return (0, inum, 0, path)
    if path not in ts_cache:
        ts_cache[path] = first_added(path)
    return (1, 0, ts_cache[path], path)


def scan():
    rows = []
    counts = defaultdict(int)
    for path in test_files():
        fs = FileScan(path)
        _TOP[path] = fs
        counts[area_of(path)] += len(fs.tests) + fs.macro_rows
        for idx, (suite, name, body) in enumerate(fs.tests):
            k = row_key(fs, body)
            if k is None:
                continue
            rows.append({"file": path, "suite": suite, "name": name, "idx": idx,
                         "prog": k[0], "body": k[1], "plen": k[2], "area": area_of(path)})
    return rows, counts


def group(rows):
    g = defaultdict(list)
    for r in rows:
        g[(r["prog"], r["body"])].append(r)
    return [v for v in g.values() if len(v) > 1]


SELFTEST_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "testdata", "test_dup_scan")
# The fixture (from review r42-rev-cull1-5233, N1) holds three FALSE pairs the
# old scanner grouped -- whitespace inside a >=40-char string (ws1, ws2), a
# second declarator (md3), a #define body naming a helper (mac4) -- between
# 1001 and 1002, and two TRUE duplicates of 1001's rows in 1003 written with
# a different C++ layout.  Exactly these groups must be found.
SELFTEST_EXPECT = {("ws2.a", "ws2.c"), ("md3.a", "md3.c")}
SELFTEST_COUNT = 12  # 10 BEZEL_TEST rows + 2 ROW(...) rows


def selftest():
    global ROOT
    ROOT = SELFTEST_DIR
    _HDR_CACHE.clear()
    _TOP.clear()
    rows, counts = scan()
    got = {tuple(sorted("%s.%s" % (r["suite"], r["name"]) for r in g)) for g in group(rows)}
    ok = True
    for g in sorted(got - SELFTEST_EXPECT):
        print("selftest: FALSE group %s" % (g,))
        ok = False
    for g in sorted(SELFTEST_EXPECT - got):
        print("selftest: MISSED true group %s" % (g,))
        ok = False
    total = sum(counts.values())
    if total != SELFTEST_COUNT:
        print("selftest: --count-rows total %d, expected %d" % (total, SELFTEST_COUNT))
        ok = False
    print("selftest: %s (%d groups found, %d expected, false groups: %d; rows counted: %d)"
          % ("PASS" if ok else "FAIL", len(got), len(SELFTEST_EXPECT),
             len(got - SELFTEST_EXPECT), total))
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json")
    ap.add_argument("--exclude", nargs="*", default=[], help="test files to treat as excluded")
    ap.add_argument("--exclude-from", help="file with one excluded test path per line")
    ap.add_argument("--count-rows", action="store_true")
    ap.add_argument("--min-program", type=int, default=0)
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    excluded = set(a.exclude)
    if a.exclude_from:
        with open(a.exclude_from) as f:
            excluded |= {x.strip() for x in f if x.strip()}
    rows, counts = scan()
    if a.count_rows:
        for k in AREAS:
            print("%-10s %d" % (k, counts.get(k, 0)))
        print("%-10s %d" % ("total", sum(counts.values())))
    groups = group(rows)
    ts_cache = {}
    result = []
    for g in groups:
        g.sort(key=lambda r: (keep_order_key(r["file"], ts_cache), r["idx"]))
        # same lowest issue number in two files: the file added first wins
        top = keep_order_key(g[0]["file"], ts_cache)[:2]
        tied = [r for r in g if keep_order_key(r["file"], ts_cache)[:2] == top]
        if len({r["file"] for r in tied}) > 1:
            for r in tied:
                if r["file"] not in ts_cache:
                    ts_cache[r["file"]] = first_added(r["file"])
            tied.sort(key=lambda r: (ts_cache[r["file"]], r["file"], r["idx"]))
            g[:len(tied)] = tied
        deferred = any(r["file"] in excluded for r in g)
        result.append({"keep": g[0], "delete": g[1:], "deferred": deferred})
    result.sort(key=lambda x: (x["keep"]["file"], x["keep"]["name"]))
    live = [x for x in result if not x["deferred"]]
    print("exact groups: %d (rows redundant: %d); outside the excluded set: %d (rows redundant: %d); deferred: %d"
          % (len(result), sum(len(x["delete"]) for x in result),
             len(live), sum(len(x["delete"]) for x in live), len(result) - len(live)))
    for i, x in enumerate(result, 1):
        k = x["keep"]
        print("%d.%s KEEP %s :: %s.%s" % (i, " [DEFERRED]" if x["deferred"] else "", k["file"], k["suite"], k["name"]))
        for d in x["delete"]:
            print("     drop %s :: %s.%s" % (d["file"], d["suite"], d["name"]))
    if a.json:
        with open(a.json, "w") as f:
            json.dump({"counts": counts, "groups": result}, f, indent=1)
    return 1 if live else 0



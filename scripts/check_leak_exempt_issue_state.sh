#!/usr/bin/env bash
#
# check_leak_exempt_issue_state.sh — audit / refresh the issue-state snapshot
# scripts/gate/leak_exempt_issue_state.tsv (#4557).
#
# WHY THIS IS A SEPARATE, NON-GATED SCRIPT. check_leak_exempt_status.py (the
# gate-wired check) validates every status:defect / status:residue row's
# issue: against that snapshot file, offline. It cannot call `gh` itself: the
# gate (gate_full_cycle.sh) is deliberately hermetic — no network call
# anywhere in it — and a live GitHub lookup on every cycle would make the
# gate flaky on network/auth, exactly the failure mode the gate's whole
# "build-free, ~70s, fails closed" design avoids. This script is the honest
# alternative: a READ-ONLY (by default) or refreshing (--update) companion,
# in the same non-gated-audit shape as the pre-existing
# scripts/check_issue_refs.sh — run it by hand periodically, or whenever
# #4557-style staleness is suspected (a fix landed, a lane closed an issue,
# it has just been a while).
#
# Usage:
#   scripts/check_leak_exempt_issue_state.sh            # audit only, exit 1
#                                                         #   on any CLOSED hit
#   scripts/check_leak_exempt_issue_state.sh --update    # audit, THEN rewrite
#                                                         #   the snapshot file
#
# Exit: 1 if any status:defect/status:residue row cites a CLOSED issue (the
#       #4557 headline shape) or an issue `gh` cannot resolve (dangling
#       reference — same "a dead pointer is permanent" rule check_issue_refs.sh
#       uses); 0 otherwise. --update always rewrites the snapshot regardless
#       of the audit verdict (there is nothing to "refuse" here — unlike a
#       ratchet baseline this file records FACTS, not a count that must only
#       fall; ACT on a red audit by fixing the row, not by suppressing it).

set -uo pipefail

REPO="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 1

EXEMPT="scripts/gate/sanitizer_leak_exempt.txt"
SNAPSHOT="scripts/gate/leak_exempt_issue_state.tsv"

command -v gh >/dev/null || { echo "check_leak_exempt_issue_state: gh not found" >&2; exit 2; }
[ -r "$EXEMPT" ] || { echo "check_leak_exempt_issue_state: cannot read $EXEMPT" >&2; exit 2; }

UPDATE=0
[ "${1:-}" = "--update" ] && UPDATE=1

# Every issue: token on a status:defect/status:residue row — the ONLY rows
# that need live state (status:trade rows are exempt from the whole snapshot
# by design; see sanitizer_leak_exempt.txt's own header).
issues="$(grep -oE '# status:(defect|residue) issue:[0-9]+' "$EXEMPT" \
  | grep -oE 'issue:[0-9]+' | grep -oE '[0-9]+' | sort -un)"

if [ -z "$issues" ]; then
  echo "check_leak_exempt_issue_state: no status:defect/status:residue rows with an issue: token — nothing to audit"
  exit 0
fi

dangling=0; closed=0; open_n=0
rows=""
printf '%-8s %-8s %s\n' "ISSUE" "STATE" "TITLE"
printf '%-8s %-8s %s\n' "-----" "-----" "-----"
while read -r n; do
  [ -n "$n" ] || continue
  if json="$(gh issue view "$n" --json state,title 2>/dev/null)"; then
    state="$(printf '%s' "$json" | python3 -c 'import json,sys; print(json.load(sys.stdin)["state"])')"
    title="$(printf '%s' "$json" | python3 -c 'import json,sys; print(json.load(sys.stdin)["title"])')"
  else
    state="DANGLING"
    title="(gh could not resolve this issue)"
  fi
  printf '#%-7s %-8s %.70s\n' "$n" "$state" "$title"
  rows="${rows}${n}"$'\t'"${state}"$'\n'
  case "$state" in
    OPEN) open_n=$((open_n + 1)) ;;
    CLOSED) closed=$((closed + 1)) ;;
    *) dangling=$((dangling + 1)) ;;
  esac
done <<< "$issues"

echo
echo "check_leak_exempt_issue_state: $open_n open, $closed closed, $dangling dangling"

if [ "$UPDATE" -eq 1 ]; then
  {
    echo "# leak_exempt_issue_state.tsv — OPEN/CLOSED snapshot for every issue: token"
    echo "# cited by a status:defect / status:residue row in sanitizer_leak_exempt.txt"
    echo "# (#4557). Read (and gate-enforced) by scripts/check_leak_exempt_status.py."
    echo "#"
    echo "# Regenerated by scripts/check_leak_exempt_issue_state.sh --update. Re-commit"
    echo "# in the SAME commit as whatever change moved it — an unbanked refresh is"
    echo "# indistinguishable from staleness. See that script's own header, and"
    echo "# sanitizer_leak_exempt.txt's header, for the full rationale."
    echo "#"
    echo "# asof: $(date -u +%Y-%m-%d) (gh issue view <n> --json state, this run)"
    echo "#"
    echo "# issue	state"
    printf '%s' "$rows"
  } > "$SNAPSHOT"
  echo "check_leak_exempt_issue_state: wrote $SNAPSHOT ($(printf '%s' "$rows" | grep -c .) issue(s))"
fi

if [ "$closed" -gt 0 ] || [ "$dangling" -gt 0 ]; then
  echo "check_leak_exempt_issue_state: ERROR — a status:defect/status:residue row" >&2
  echo "  cites an issue that is CLOSED or cannot be resolved (#4557). For each:" >&2
  echo "  verify the leak is actually fixed and remove the row WITH EVIDENCE, or" >&2
  echo "  re-file a fresh open tracker and update its issue: token, or reclassify" >&2
  echo "  the row status:trade with reasoning if it turns out to be deliberate." >&2
  echo "  Never hand-edit $SNAPSHOT's state column — re-run with --update." >&2
  exit 1
fi
exit 0

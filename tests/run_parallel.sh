#!/usr/bin/env bash
# Run the Bezel test suite in parallel shards, across every per-area test binary.
#
# The suite is built as SEVERAL executables (bezel_tests_<group>, one per
# tests/<area>/ group — see tests/CMakeLists.txt) so a change relinks only the
# area it touches. Each executable's harness (test_main.cpp) honours
# BEZEL_SHARD_COUNT / BEZEL_SHARD_INDEX to run a disjoint round-robin subset of
# ITS OWN registry, so the union of a binary's slices is exactly that binary's
# tests, and the union over all binaries is exactly the whole suite.
#
# Usage:
#   tests/run_parallel.sh [CONCURRENCY] [BINARY ...]
#     CONCURRENCY  max test processes alive at once (default: min(16, nproc)).
#                  This is the RESOURCE cap the gate tunes — scripts/gate.sh
#                  lowers it to 8 for the ASan pass because ASan shards are
#                  memory-bound — NOT the number of slices: every binary is
#                  split into CONCURRENCY round-robin slices and the slices run
#                  through one bounded queue.
#     BINARY...    explicit binaries (default: every binary listed in the
#                  generated manifest build/tests/test_binaries.txt).
#   BEZEL_TEST_FILTER=<substr> is passed through to each shard.
#   BEZEL_TEST_LIST=<file> (exact suite.name lines, #2100) likewise inherits into
#   every shard; each binary then reports an explicit "N selected" field and the
#   integrity accounting below compares ran against the SELECTED count PER
#   BINARY (a binary holding none of the listed tests legitimately selects 0),
#   while "did the list select anything at all" and the phantom-name warning are
#   GLOBAL — no single binary can see the whole list.
#
# Exit status is 0 only if every shard exited 0 and no test failed.
set -u

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
manifest="$repo_root/build/tests/test_binaries.txt"
ncpu="$(nproc)"
default_conc=$(( ncpu < 16 ? ncpu : 16 ))
conc="${1:-$default_conc}"
# conc must be an integer >= 1: conc=0 launches no shards, writes no summaries,
# and every accounting check passes vacuously -> exit 0 over NOTHING (the same
# Plan-A 5.1 "PASS>0" class conformance's guard closes). A non-numeric conc
# would also misbehave in the arithmetic below.
if ! [[ "$conc" =~ ^[0-9]+$ ]] || (( conc < 1 )); then
  echo "error: conc must be an integer >= 1 (got '$conc')" >&2
  exit 2
fi
shift || true

# ── which binaries ──────────────────────────────────────────────────────────
# Default: the CMake-generated manifest — the same list CMake built, so a binary
# can never be silently omitted from a run. An explicit list (used by
# scripts/agent_check.sh for a single-area lane check) overrides it.
names=(); bins=()
# Labels must be unique — they name this run's per-shard log files. Group names
# from the manifest are unique by construction; an explicit list can repeat a
# path, so disambiguate rather than let two binaries share a log.
add_bin() { # $1 = label, $2 = path
    local label="$1" n=2
    while printf '%s\n' "${names[@]:-}" | grep -qxF -- "$label"; do
        label="$1-$n"; n=$(( n + 1 ))
    done
    names+=("$label"); bins+=("$2")
}
if [[ "$#" -gt 0 ]]; then
    for b in "$@"; do add_bin "$(basename "$b")" "$b"; done
else
    if [[ ! -r "$manifest" ]]; then
        echo "error: test-binary manifest not found: $manifest" >&2
        echo "       (it is generated by CMake — configure+build first:" >&2
        echo "        cmake -S . -B build -DCMAKE_BUILD_TYPE=RelWithDebInfo && cmake --build build --target bezel_tests)" >&2
        exit 2
    fi
    while IFS=$'\t' read -r n p w; do
        [[ -z "${n:-}" ]] && continue
        add_bin "$n" "$p"
    done < "$manifest"
fi
nbin="${#bins[@]}"
if [[ "$nbin" -eq 0 ]]; then
    echo "error: no test binaries to run (empty manifest $manifest)" >&2
    exit 2
fi
for (( b = 0; b < nbin; b++ )); do
    if [[ ! -x "${bins[$b]}" ]]; then
        echo "error: test binary not found/executable: ${bins[$b]}" >&2
        exit 2
    fi
done

logdir="$(mktemp -d "${TMPDIR:-/tmp}/bezel_shards.XXXXXX")"
# fix #3010: RETAIN THE PER-SHARD LOGS WHEN THE RUN WAS NOT CLEAN.
#
# This was an unconditional `trap 'rm -rf "$logdir"' EXIT`, so every per-shard
# log was destroyed on EVERY exit — pass or fail. That is the same defect
# #3001 just fixed one level up (gate_full_cycle.sh overwrote each distrusted
# attempt's log), and it has the same consequence: an undercount leaves nothing
# to look at, so it can never be diagnosed. #3001's open question 7 — "why does
# the gtests harvest regex fail on 26 passing runs?" — is unanswerable today
# precisely because these logs were rm -rf'd.
#
# Clean run: reap as before, nothing is lost. Non-clean: move the directory
# aside and say where it went, once.
_rp_keep() {
  local rc=$?
  if [ "$rc" -eq 0 ]; then
    rm -rf "$logdir"
  else
    local keep="${BEZEL_SHARD_LOG_KEEP:-/var/tmp/bezel-scratch/shard-logs}"
    if mkdir -p "$keep" 2>/dev/null && mv "$logdir" "$keep/$(date +%Y%m%d-%H%M%S)-rc$rc" 2>/dev/null; then
      echo "run_parallel: exit rc=$rc — per-shard logs KEPT in $keep/ (see #3010)" >&2
    else
      rm -rf "$logdir"
    fi
  fi
  return $rc
}
trap _rp_keep EXIT

njobs=$(( nbin * conc ))
echo "Running $nbin test binaries × $conc slices = $njobs shards, $conc at a time (of $ncpu cores)..."
start=$(date +%s)

# ── the queue ───────────────────────────────────────────────────────────────
# Every binary is split into $conc round-robin slices; the slices are launched
# through a semaphore that keeps at most $conc processes alive, so the RESOURCE
# footprint is identical to the old single-binary run ($conc processes) while
# the load stays balanced regardless of how unevenly tests are spread across
# binaries. Binaries come from the manifest largest-first, so the longest jobs
# start first and the tail is short.
#
# Each shard gets its OWN TMPDIR. Many native/AOT tests write temp files with a
# fixed per-process stem (e.g. bezel_380_0.o) via std::filesystem::
# temp_directory_path(), which honours $TMPDIR. Without isolation two shards
# would write the same path concurrently and clobber each other; a private
# TMPDIR per shard makes those fixed stems collision-free with no test changes.
#
# Each shard writes its own exit status to $logdir/rc.<name>.<i> rather than
# relying on `wait` to hand it back: the semaphore below reaps with `wait -n`,
# which cannot tell you WHICH job finished.
running=0
for (( b = 0; b < nbin; b++ )); do
    for (( i = 0; i < conc; i++ )); do
        shard_tmp="$logdir/tmp.${names[$b]}.$i"
        mkdir -p "$shard_tmp"
        # Per-shard timeout: a DEADLOCKED test (e.g. a cross-domain-mutex
        # contention race, #1609) otherwise hangs `wait` below forever and
        # wedges the whole gate. timeout kills the hung shard (exit 124/137 ->
        # counted as a crashed shard -> the gate's flake arbitration re-runs it).
        #
        # The subshell records the shard's OWN wall time (a SHARD_ELAPSED marker
        # appended to its log, surfaced below) — observation only.
        (
            _s=$(awk '{print $1; exit}' /proc/uptime 2>/dev/null || date +%s)
            # per #3012 Phase 2a: opt each shard into the structured JSON
            # summary. test_main.cpp writes it ALONGSIDE the (unchanged) legacy
            # stderr line; the agreement check below compares the two. The path
            # lives in $logdir so it shares the run's lifetime (reaped on a
            # clean exit, kept with the logs on a failure).
            TMPDIR="$shard_tmp" BEZEL_SHARD_COUNT="$conc" BEZEL_SHARD_INDEX="$i" \
                BEZEL_SHARD_SUMMARY="$logdir/summary.${names[$b]}.$i.json" \
                timeout -k 10 "${BEZEL_SHARD_TIMEOUT:-300}" "${bins[$b]}" \
                > "$logdir/shard.${names[$b]}.$i.log" 2>&1
            _rc=$?
            _e=$(awk '{print $1; exit}' /proc/uptime 2>/dev/null || date +%s)
            awk "BEGIN{printf \"SHARD_ELAPSED %.2f\\n\", $_e-$_s}" \
                >> "$logdir/shard.${names[$b]}.$i.log"
            echo "$_rc" > "$logdir/rc.${names[$b]}.$i"
        ) &
        running=$(( running + 1 ))
        if (( running >= conc )); then wait -n; running=$(( running - 1 )); fi
    done
done
wait

# ── per-binary integrity accounting (Phase 2c: reads structured JSON) ────────
# Every check the single-binary runner made is made here PER BINARY, because
# each binary has its own registry and its own expected total. A missing rc
# file is itself a crash (the subshell died before recording one).
#
# Each shard writes a structured JSON summary (BEZEL_SHARD_SUMMARY, Phase 2a)
# ALONGSIDE its legacy "N passed, ... T total" stderr line. scripts/gate/
# summary.py `account` reads those JSONs + the rc.<name>.<i> files and produces
# the accounting the legacy per-shard grep used to (run_parallel pre-Phase-2c):
# grand totals, per-binary ran/expected, and the integrity flags + defect lists
# that drive this script's exit and the GATE FAILURE banner below.
#
# Crash detection reads the rc FILE, not the JSON `rc` field: test_main.cpp
# writes the JSON just before `return` (test_main.cpp:281-318), so a shard
# killed mid-run (segfault / timeout) never reaches the write. The rc file is
# the only signal that catches a kill. summary_ok demands EVERY shard wrote a
# JSON summary — a shard that exits 0 yet wrote none validated NONE of its
# slice, so a "0 failed" aggregate is not trustworthy regardless of exit code;
# that is the safety basis for the shard-authoritative gate (scripts/gate.sh,
# #1861) having no serial backstop.
#
# DUAL-READ (the "rewriting the engine while flying" rule, per #3012): the
# legacy stderr line is still dual-emitted, and summary.check_agreement pairs
# each JSON with its legacy line PER SHARD. Per-shard agreement TRANSITIVELY
# guarantees the accounting sums agree (0 per-shard mismatch => identical
# totals/flags — passed/failed/total/selected and presence are all compared per
# shard, so summing them can't diverge). So a 0-mismatch assertion here IS the
# equivalence proof. A mismatch is a #3012-style stream/parse divergence — fail
# LOUD rather than read ambiguous data. Once N gates prove 0-mismatch the
# assertion + the legacy dual-emit are removed (the ratchet this lands).
if ! command -v python3 >/dev/null 2>&1; then
    echo "run_parallel: python3 not found — Phase 2c accounting requires it (see #3012)" >&2
    exit 1
fi
_account_subset=0
[[ -n "${BEZEL_TEST_LIST:-}" ]] && _account_subset=1
# Build the argv as an array so a BEZEL_RUN_SUMMARY path with spaces survives
# intact (the gate sets BEZEL_RUN_SUMMARY=$S/gate_run_summary.json so its
# harvest can read the merged result instead of grepping this script's stdout —
# the per-shard JSONs live in $logdir and are reaped on a clean exit).
_account_args=(gate.summary account "$logdir" --conc "$conc")
[[ "$_account_subset" -eq 1 ]] && _account_args+=(--subset)
# narrow #3222: pass the configured per-shard ceiling so account() can classify
# timeout-killed shards (rc in {124,137} AND elapsed near the ceiling) into
# `timed_out_shards` rather than `crashed_shards`. Empty/zero leaves the
# pre-#3222 behaviour (a timed-out shard reads as a generic crash) — this
# matches the unit tests that don't care about the ceiling classification.
[[ -n "${BEZEL_SHARD_TIMEOUT:-}" ]] && _account_args+=(--shard-timeout "$BEZEL_SHARD_TIMEOUT")
[[ -n "${BEZEL_RUN_SUMMARY:-}" ]] && _account_args+=(--run-summary "$BEZEL_RUN_SUMMARY")
_account_args+=(-- "${names[@]}")
if ! _rp_out=$(PYTHONPATH="$repo_root/scripts" python3 -m "${_account_args[@]}" 2>"$logdir/account.err"); then
    echo "run_parallel: summary.py account failed — see $logdir/account.err" >&2
    cat "$logdir/account.err" >&2
    exit 1
fi
eval "$_rp_out"

# Dual-read assertion: 0 per-shard JSON/legacy mismatch => the structured
# accounting equals the legacy grep accounting on every field. check exits
# nonzero on any mismatch; on success it prints the human-readable agreement
# line (relayed below for the log).
if ! _agr=$(PYTHONPATH="$repo_root/scripts" python3 -m gate.summary check "$logdir" 2>&1); then
    echo "############################################################"
    echo "## GATE FAILURE: shard-summary MISMATCH — structured JSON != legacy line"
    echo "##   The Phase 2c reader disagrees with the legacy grep; the result is"
    echo "##   NOT trustworthy. Per-shard agreement details:"
    echo "$_agr" >&2
    echo "############################################################"
    exit 1
fi
echo "$_agr"

# Map the sourceable rp_* output onto the variables the banner/table/exit below
# consume. Kept identical to the pre-Phase-2c names so the reporting surface
# (banner literal, TOTAL line, per-binary table) is byte-for-byte unchanged —
# the switch is in the READER, not the reporting (gate_full_cycle.sh:96 greps
# the banner; gate.sh:831/785 greps the TOTAL/shard-timing lines).
total_pass=$rp_total_pass
total_fail=$rp_total_fail
shard_rc=$(( 1 - rp_shard_rc_ok ))   # shard_rc=1 iff a crash occurred
count_ok=$rp_count_ok
summary_ok=$rp_summary_ok
subset_mode=$rp_subset_mode
global_selected=$rp_global_selected
ran=$rp_ran
expected_all=$rp_expected_all
registry_all=$rp_registry_all
crashed_shards=("${rp_crashed_shards[@]}")
# narrow #3222: ceiling-killed shards are sourced from the same rp_* eval
# (account() emits rp_timed_out_shards=(...)). Empty when no shard tripped
# the ceiling — the banner omits the section entirely in that case.
timed_out_shards=("${rp_timed_out_shards[@]:-}")
missing_summary_shards=("${rp_missing_summary_shards[@]}")
undercount_bins=("${rp_undercount_bins[@]}")
declare -a bin_pass bin_fail bin_expected bin_registry
bin_pass=("${rp_bin_pass[@]}")
bin_fail=("${rp_bin_fail[@]}")
bin_expected=("${rp_bin_expected[@]}")
bin_registry=("${rp_bin_registry[@]}")
# An EMPTY selection is never a pass (#2100): a subset run that selected 0
# tests validated nothing. GLOBAL — a single binary selecting 0 is normal (it
# holds none of the listed tests); only "no binary selected anything" is the
# empty-list bug.
subset_empty=$rp_subset_empty

# Preserve the per-shard crash notice on stderr (no external consumer greps it,
# but it surfaces a crash immediately, ahead of the banner below).
for _cs in "${crashed_shards[@]:-}"; do
    [[ -n "$_cs" ]] && echo "shard $_cs exited nonzero (crash or test failure)" >&2
done
# narrow #3222: surface ceiling-killed shards distinctly (the ASan ceiling
# is the most likely reason for a shard dying in a healthy suite — see the
# gate.sh:650 multiplier). The wording differs from the generic crash line
# above so an operator scanning stderr knows it is an INFRA defect (raise
# the ceiling), not a SUITE defect (chase the test).
for _ts in "${timed_out_shards[@]:-}"; do
    [[ -n "$_ts" ]] && echo "shard $_ts TIMED OUT at the per-shard ceiling (BEZEL_SHARD_TIMEOUT=#3222)" >&2
done

end=$(date +%s)

# Surface any failing test names across all shards.
fail_lines="$(grep -a -hE '^\[ FAIL \]' "$logdir"/shard.*.log 2>/dev/null || true)"
if [[ -n "$fail_lines" ]]; then
    echo "--- failing tests ---"
    echo "$fail_lines"
fi

# Phantom-name warning + GATE FAILURE banner (#2100, #1861) — the
# culprit-extraction grep + the distinct-names warning live in gate.summary
# (clearer and testable in Python). The 'shard crash / undercount' +
# 'WARNING: only' literals are LOAD-BEARING — gate_full_cycle.sh:79,
# gate.sh:106/637, agent_check.sh:266 grep them.
# per #2100 (the distinct-names rule) and #1608 (the last-[ RUN ]-line culprit
# is a MISATTRIBUTION, but documented behavior consumers expect — preserved).

# Distinct listed-name count (subset mode, no filter, readable list). sort -u so
# a repeated list line does not read as a phantom, matching the binary's own set
# semantics.
listed=0
_rp_py_phantom=""
if [[ "$subset_mode" -eq 1 && -z "${BEZEL_TEST_FILTER:-}" && -r "${BEZEL_TEST_LIST:-}" ]]; then
    listed="$(sed -E 's/[[:space:]]+$//; s/^[[:space:]]+//' "$BEZEL_TEST_LIST" 2>/dev/null | grep . | sort -u | grep -c .)"
    # Phantom-name warning (#2100): a listed name matching NO registered test is
    # a silently-dropped test. Computed HERE, not in the binary — with the suite
    # split across binaries no single binary can tell a phantom from a name in a
    # sibling binary. Only meaningful with no substring filter: under list+filter
    # composition, selected < listed is the filter working, not phantom names.
    _rp_py_phantom="$(PYTHONPATH="$repo_root/scripts" python3 -m gate.summary format-phantom --listed "$listed" --selected "$global_selected")"
fi
[[ -n "$_rp_py_phantom" ]] && printf '%s\n' "$_rp_py_phantom"

# GATE INTEGRITY (#1861): a crashed shard (segfault / uncaught exit(70)) silently
# drops its remaining tests. Detect three ways — nonzero shard exit, a per-binary
# count short of its total, a shard that printed no summary — and fail LOUDLY,
# naming the crashed shard and the last test it ran. The culprit extraction
# (grep RUN | tail -1 | sed) now lives in summary.py; this call is the authority.
_rp_py_failure="$(PYTHONPATH="$repo_root/scripts" python3 -m gate.summary format-failure \
    --ran "$ran" --expected "$expected_all" --nbin "$nbin" \
    --subset-empty "$subset_empty" --njobs "$njobs" \
    --undercount "${undercount_bins[@]}" \
    --missing-summary "${missing_summary_shards[@]}" \
    --crashed "${crashed_shards[@]}" \
    --timed-out "${timed_out_shards[@]:-}" \
    --logdir "$logdir")"
[[ -n "$_rp_py_failure" ]] && printf '%s\n' "$_rp_py_failure"

# Per-shard wall times (observation only — lets the gate's timing log spot shard
# imbalance). Harvested from each shard's SHARD_ELAPSED marker before cleanup.
for (( b = 0; b < nbin; b++ )); do
    for (( i = 0; i < conc; i++ )); do
        et="$(grep -a -oE 'SHARD_ELAPSED [0-9.]+' "$logdir/shard.${names[$b]}.$i.log" 2>/dev/null | awk '{print $2}' | tail -1)"
        [[ -n "$et" ]] && echo "shard ${names[$b]}.$i: ${et}s"
    done
done

echo "============================================================"
for (( b = 0; b < nbin; b++ )); do
    note=""
    [[ "$subset_mode" -eq 1 ]] && note="  [${bin_expected[$b]} selected of ${bin_registry[$b]} registered]"
    printf '  %-12s %6d passed, %d failed%s\n' \
        "${names[$b]}" "${bin_pass[$b]}" "${bin_fail[$b]}" "$note"
done
subset_note=""
[[ "$subset_mode" -eq 1 ]] && subset_note="  [SUBSET: $global_selected selected of $registry_all registered]"
echo "TOTAL: $total_pass passed, $total_fail failed  (across $njobs shards, $((end - start))s)$subset_note"
echo "============================================================"

# Per-shard JSON/legacy agreement was ASSERTED in the accounting block above
# (a mismatch fails the run loud). The legacy stderr line is still dual-emitted
# by test_main.cpp as the fallback the assertion compares against; removing
# that dual-emit + the legacy line is the post-N-gates ratchet (per #3012).

if [[ "$shard_rc" -ne 0 || "$total_fail" -ne 0 || "$count_ok" -eq 0 || "$summary_ok" -eq 0 || "$subset_empty" -eq 1 ]]; then
    exit 1
fi
exit 0

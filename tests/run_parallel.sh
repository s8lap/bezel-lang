#!/usr/bin/env bash
# Run the Bezel test suite in parallel shards, across every per-area test binary.
#
# The suite is built as SEVERAL executables (bezel_tests_<group>, one per
# tests/<area>/ group — see tests/CMakeLists.txt) so a change relinks only the
# area it touches. Each executable's harness (test_main.cpp) honours
# BEZEL_SHARD_COUNT / BEZEL_SHARD_INDEX to run a disjoint round-robin subset of
# ITS OWN registry, so the union of a binary's slices is exactly that binary's
# tests, and the union over all binaries is exactly the whole suite.
#
# Usage:
#   tests/run_parallel.sh [CONCURRENCY] [BINARY ...]
#     CONCURRENCY  max test processes alive at once (default: min(16, nproc)).
#                  This is the RESOURCE cap the gate tunes — scripts/gate.sh
#                  lowers it to 8 for the ASan pass because ASan shards are
#                  memory-bound — NOT the number of slices: every binary is
#                  split into CONCURRENCY round-robin slices and the slices run
#                  through one bounded queue.
#     BINARY...    explicit binaries (default: every binary listed in the
#                  generated manifest build/tests/test_binaries.txt).
#   BEZEL_TEST_FILTER=<substr> is passed through to each shard.
#   BEZEL_TEST_LIST=<file> (exact suite.name lines, #2100) likewise inherits into
#   every shard; each binary then reports an explicit "N selected" field and the
#   integrity accounting below compares ran against the SELECTED count PER
#   BINARY (a binary holding none of the listed tests legitimately selects 0),
#   while "did the list select anything at all" and the phantom-name warning are
#   GLOBAL — no single binary can see the whole list.
#
# Exit status is 0 only if every shard exited 0 and no test failed.
set -u

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
manifest="$repo_root/build/tests/test_binaries.txt"
ncpu="$(nproc)"
default_conc=$(( ncpu < 16 ? ncpu : 16 ))
conc="${1:-$default_conc}"
shift || true

# ── which binaries ──────────────────────────────────────────────────────────
# Default: the CMake-generated manifest — the same list CMake built, so a binary
# can never be silently omitted from a run. An explicit list (used by
# scripts/agent_check.sh for a single-area lane check) overrides it.
names=(); bins=()
# Labels must be unique — they name this run's per-shard log files. Group names
# from the manifest are unique by construction; an explicit list can repeat a
# path, so disambiguate rather than let two binaries share a log.
add_bin() { # $1 = label, $2 = path
    local label="$1" n=2
    while printf '%s\n' "${names[@]:-}" | grep -qxF -- "$label"; do
        label="$1-$n"; n=$(( n + 1 ))
    done
    names+=("$label"); bins+=("$2")
}
if [[ "$#" -gt 0 ]]; then
    for b in "$@"; do add_bin "$(basename "$b")" "$b"; done
else
    if [[ ! -r "$manifest" ]]; then
        echo "error: test-binary manifest not found: $manifest" >&2
        echo "       (it is generated by CMake — configure+build first:" >&2
        echo "        cmake -S . -B build && cmake --build build --target bezel_tests)" >&2
        exit 2
    fi
    while IFS=$'\t' read -r n p w; do
        [[ -z "${n:-}" ]] && continue
        add_bin "$n" "$p"
    done < "$manifest"
fi
nbin="${#bins[@]}"
if [[ "$nbin" -eq 0 ]]; then
    echo "error: no test binaries to run (empty manifest $manifest)" >&2
    exit 2
fi
for (( b = 0; b < nbin; b++ )); do
    if [[ ! -x "${bins[$b]}" ]]; then
        echo "error: test binary not found/executable: ${bins[$b]}" >&2
        exit 2
    fi
done

logdir="$(mktemp -d "${TMPDIR:-/tmp}/bezel_shards.XXXXXX")"
trap 'rm -rf "$logdir"' EXIT

njobs=$(( nbin * conc ))
echo "Running $nbin test binaries × $conc slices = $njobs shards, $conc at a time (of $ncpu cores)..."
start=$(date +%s)

# ── the queue ───────────────────────────────────────────────────────────────
# Every binary is split into $conc round-robin slices; the slices are launched
# through a semaphore that keeps at most $conc processes alive, so the RESOURCE
# footprint is identical to the old single-binary run ($conc processes) while
# the load stays balanced regardless of how unevenly tests are spread across
# binaries. Binaries come from the manifest largest-first, so the longest jobs
# start first and the tail is short.
#
# Each shard gets its OWN TMPDIR. Many native/AOT tests write temp files with a
# fixed per-process stem (e.g. bezel_380_0.o) via std::filesystem::
# temp_directory_path(), which honours $TMPDIR. Without isolation two shards
# would write the same path concurrently and clobber each other; a private
# TMPDIR per shard makes those fixed stems collision-free with no test changes.
#
# Each shard writes its own exit status to $logdir/rc.<name>.<i> rather than
# relying on `wait` to hand it back: the semaphore below reaps with `wait -n`,
# which cannot tell you WHICH job finished.
running=0
for (( b = 0; b < nbin; b++ )); do
    for (( i = 0; i < conc; i++ )); do
        shard_tmp="$logdir/tmp.${names[$b]}.$i"
        mkdir -p "$shard_tmp"
        # Per-shard timeout: a DEADLOCKED test (e.g. a cross-domain-mutex
        # contention race, #1609) otherwise hangs `wait` below forever and
        # wedges the whole gate. timeout kills the hung shard (exit 124/137 ->
        # counted as a crashed shard -> the gate's flake arbitration re-runs it).
        #
        # The subshell records the shard's OWN wall time (a SHARD_ELAPSED marker
        # appended to its log, surfaced below) — observation only.
        (
            _s=$(awk '{print $1; exit}' /proc/uptime 2>/dev/null || date +%s)
            TMPDIR="$shard_tmp" BEZEL_SHARD_COUNT="$conc" BEZEL_SHARD_INDEX="$i" \
                timeout -k 10 "${BEZEL_SHARD_TIMEOUT:-300}" "${bins[$b]}" \
                > "$logdir/shard.${names[$b]}.$i.log" 2>&1
            _rc=$?
            _e=$(awk '{print $1; exit}' /proc/uptime 2>/dev/null || date +%s)
            awk "BEGIN{printf \"SHARD_ELAPSED %.2f\\n\", $_e-$_s}" \
                >> "$logdir/shard.${names[$b]}.$i.log"
            echo "$_rc" > "$logdir/rc.${names[$b]}.$i"
        ) &
        running=$(( running + 1 ))
        if (( running >= conc )); then wait -n; running=$(( running - 1 )); fi
    done
done
wait

# ── per-binary integrity accounting ─────────────────────────────────────────
# Every check the single-binary runner made is made here PER BINARY, because
# each binary has its own registry and its own expected total. A missing rc file
# is itself a crash (the subshell died before recording one).
#
# Each shard prints "P passed, F failed[, S filtered][, N selected] (shard i/n),
# T total". T is that binary's whole registry size (identical across its
# shards) — capture it as the EXPECTED count so a shard that dies mid-run (its
# passed count missing) is detected as an undercount rather than passing
# silently.
#
# summaries_seen ALSO records, EXPLICITLY, how many shards printed a completion
# summary at all. A shard that exits 0 yet never printed a summary — e.g. a path
# that abort()s or exit()s the harness mid-loop — drops its whole slice while
# evading detection: crashed_shards misses it (exit 0), and the ran!=expected
# undercount check can only catch it when SOME OTHER shard of the same binary
# established that binary's expected total. This direct "every shard must
# complete" check closes that window unconditionally, and is the safety basis
# for the shard-authoritative gate (scripts/gate.sh, #1861) having no serial
# backstop. It is purely additive: a healthy run prints nothing new below.
total_pass=0
total_fail=0
shard_rc=0
count_ok=1
summary_ok=1
subset_mode=0
global_selected=0
crashed_shards=()
missing_summary_shards=()
undercount_bins=()
declare -a bin_pass bin_fail bin_expected bin_registry bin_what
for (( b = 0; b < nbin; b++ )); do
    name="${names[$b]}"
    b_pass=0; b_fail=0; b_registry=0; b_selected=0; b_summaries=0; b_subset=0
    for (( i = 0; i < conc; i++ )); do
        log="$logdir/shard.$name.$i.log"
        rcf="$logdir/rc.$name.$i"
        rc="$(cat "$rcf" 2>/dev/null)"
        if [[ "${rc:-1}" -ne 0 ]]; then
            echo "shard $name/$i exited nonzero (crash or test failure)" >&2
            shard_rc=1
            crashed_shards+=("$name/$i")
        fi
        line="$(grep -a -E '^[0-9]+ passed, [0-9]+ failed' "$log" 2>/dev/null | tail -1)"
        if [[ -n "$line" ]]; then
            b_summaries=$(( b_summaries + 1 ))
        else
            missing_summary_shards+=("$name/$i")
        fi
        p="$(sed -E 's/^([0-9]+) passed.*/\1/' <<<"$line")"
        f="$(sed -E 's/^[0-9]+ passed, ([0-9]+) failed.*/\1/' <<<"$line")"
        t="$(sed -E 's/.*, ([0-9]+) total.*/\1/' <<<"$line")"
        b_pass=$(( b_pass + ${p:-0} ))
        b_fail=$(( b_fail + ${f:-0} ))
        [[ "${t:-0}" -gt "$b_registry" ]] && b_registry="$t"
        # Subset marker (#2100): a BEZEL_TEST_LIST run reports ", N selected".
        # Like the registry total, the selected count is identical across a
        # binary's shards (each re-walks the whole registry with the same list)
        # — max is the harvest.
        if [[ "$line" == *" selected"* ]]; then
            subset_mode=1; b_subset=1
            s="$(grep -oE '[0-9]+ selected' <<<"$line" | grep -oE '^[0-9]+')"
            [[ "${s:-0}" -gt "$b_selected" ]] && b_selected="$s"
        fi
    done
    # Subset accounting (#2100): under BEZEL_TEST_LIST the drop-detection
    # contract is "every SELECTED test ran" — the registry total would
    # mechanically false-fail any subset.
    if [[ "$b_subset" -eq 1 ]]; then
        b_expected="$b_selected"; bin_what[$b]="selected"
        global_selected=$(( global_selected + b_selected ))
    else
        b_expected="$b_registry"; bin_what[$b]="registered"
    fi
    b_ran=$(( b_pass + b_fail ))
    if [[ "$b_expected" -gt 0 && "$b_ran" -ne "$b_expected" ]]; then
        count_ok=0
        undercount_bins+=("$name: ran $b_ran of $b_expected ${bin_what[$b]}")
    fi
    # EVERY shard must have printed a completion summary. A shard missing one
    # validated NONE of its slice, so a "0 failed" aggregate is not trustworthy
    # regardless of exit code — stricter than the undercount check (which needs
    # another shard of the SAME binary to have established the expected total)
    # and never lets a dropped slice pass green.
    [[ "$b_summaries" -ne "$conc" ]] && summary_ok=0
    bin_pass[$b]=$b_pass; bin_fail[$b]=$b_fail
    bin_expected[$b]=$b_expected; bin_registry[$b]=$b_registry
    total_pass=$(( total_pass + b_pass ))
    total_fail=$(( total_fail + b_fail ))
done
ran=$(( total_pass + total_fail ))
expected_all=0
registry_all=0
for (( b = 0; b < nbin; b++ )); do
    expected_all=$(( expected_all + bin_expected[b] ))
    registry_all=$(( registry_all + bin_registry[b] ))
done

# An EMPTY selection is never a pass: a subset run that selected 0 tests
# validated nothing, so it fails loudly instead of reading "0 failed". This is
# GLOBAL — a single binary selecting 0 is normal (it holds none of the listed
# tests); only "no binary selected anything" is the empty-list bug.
subset_empty=0
if [[ "$subset_mode" -eq 1 && "$global_selected" -eq 0 ]]; then
    subset_empty=1
fi

end=$(date +%s)

# Surface any failing test names across all shards.
fail_lines="$(grep -a -hE '^\[ FAIL \]' "$logdir"/shard.*.log 2>/dev/null || true)"
if [[ -n "$fail_lines" ]]; then
    echo "--- failing tests ---"
    echo "$fail_lines"
fi

# Phantom-name warning (#2100). A listed name matching NO registered test is a
# silently-dropped test (typo, rename, or a selector parse artifact). It is
# computed HERE, not in the binary, because with the suite split across binaries
# no single binary can tell a phantom name from a name that lives in a sibling
# binary — each would warn about every test it does not own. Only meaningful
# with no substring filter: under list+filter composition, selected < listed is
# the filter working, not phantom names. The gate and agent_check tripwires grep
# for the 'WARNING: only' text, which is preserved verbatim.
if [[ "$subset_mode" -eq 1 && -z "${BEZEL_TEST_FILTER:-}" && -r "${BEZEL_TEST_LIST:-}" ]]; then
    # Count DISTINCT names, matching the binary's own set semantics — a list
    # with a repeated line must not read as a phantom.
    listed="$(sed -E 's/[[:space:]]+$//; s/^[[:space:]]+//' "$BEZEL_TEST_LIST" 2>/dev/null | grep . | sort -u | grep -c .)"
    if [[ "$global_selected" -lt "${listed:-0}" ]]; then
        echo "bezel_tests: WARNING: only $global_selected of $listed listed tests matched the registry (BEZEL_TEST_LIST has phantom/renamed names)"
    fi
fi

# GATE INTEGRITY: a crashed shard (uncaught exception -> runtime exit(70), or a
# segfault) kills the host process and silently drops its remaining tests. Detect
# it three ways — a nonzero shard exit, a PER-BINARY count that falls short of
# that binary's total, and a shard that printed no summary — and fail LOUDLY,
# naming the crashed shard and the last test it ran (the crash culprit). Without
# this the summary reads "0 failed" on an undercount.
if [[ "${#crashed_shards[@]}" -gt 0 || "$count_ok" -eq 0 || "$summary_ok" -eq 0 || "$subset_empty" -eq 1 ]]; then
    echo "############################################################"
    echo "## GATE FAILURE: shard crash / undercount — result is NOT trustworthy"
    echo "##   ran $ran of $expected_all expected tests ($(( expected_all - ran )) unaccounted) across $nbin binaries"
    for u in "${undercount_bins[@]:-}"; do
        [[ -n "$u" ]] && echo "##   UNDERCOUNT $u"
    done
    if [[ "$subset_empty" -eq 1 ]]; then
        echo "##   SUBSET run selected 0 tests in EVERY binary (empty/unmatched BEZEL_TEST_LIST) — nothing was validated"
    fi
    if [[ "$summary_ok" -eq 0 ]]; then
        echo "##   ${#missing_summary_shards[@]} of $njobs shards printed NO completion summary (slice not validated): shard(s) ${missing_summary_shards[*]}"
    fi
    for s in "${crashed_shards[@]:-}"; do
        [[ -n "$s" ]] || continue
        last="$(grep -a -E '^\[ RUN' "$logdir/shard.${s%/*}.${s#*/}.log" 2>/dev/null | tail -1 | sed -E 's/^\[ RUN  \] //')"
        echo "##   shard $s exited nonzero — died on: ${last:-<none>}"
    done
    echo "############################################################"
fi

# Per-shard wall times (observation only — lets the gate's timing log spot shard
# imbalance). Harvested from each shard's SHARD_ELAPSED marker before cleanup.
for (( b = 0; b < nbin; b++ )); do
    for (( i = 0; i < conc; i++ )); do
        et="$(grep -a -oE 'SHARD_ELAPSED [0-9.]+' "$logdir/shard.${names[$b]}.$i.log" 2>/dev/null | awk '{print $2}' | tail -1)"
        [[ -n "$et" ]] && echo "shard ${names[$b]}.$i: ${et}s"
    done
done

echo "============================================================"
for (( b = 0; b < nbin; b++ )); do
    note=""
    [[ "$subset_mode" -eq 1 ]] && note="  [${bin_expected[$b]} selected of ${bin_registry[$b]} registered]"
    printf '  %-12s %6d passed, %d failed%s\n' \
        "${names[$b]}" "${bin_pass[$b]}" "${bin_fail[$b]}" "$note"
done
subset_note=""
[[ "$subset_mode" -eq 1 ]] && subset_note="  [SUBSET: $global_selected selected of $registry_all registered]"
echo "TOTAL: $total_pass passed, $total_fail failed  (across $njobs shards, $((end - start))s)$subset_note"
echo "============================================================"

if [[ "$shard_rc" -ne 0 || "$total_fail" -ne 0 || "$count_ok" -eq 0 || "$summary_ok" -eq 0 || "$subset_empty" -eq 1 ]]; then
    exit 1
fi
exit 0

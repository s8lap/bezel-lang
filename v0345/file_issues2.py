import json,subprocess,sys,re
d=sys.argv[1].rstrip('/')+'/'
nums={}
try: nums=json.load(open(d+'nums.json'))
except: pass
FOOT='\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
def refs(t): return set(re.findall(r'\{\{ISSUE:([^}]*)\}\}',t))
def sub(t):
    if not t.rstrip().endswith('(https://claude.ai/code)_'): t=t.rstrip()+FOOT
    return re.sub(r'\{\{ISSUE:([^}]*)\}\}', lambda m: '#'+str(nums[m.group(1)]), t)
items=json.load(open(d+'questions.json'))+[e for e in json.load(open(d+'trackers.json')) if e.get('action')=='create']
keys={e['key'] for e in items}
pending=[e for e in items if e['key'] not in nums]
while pending:
    ready=[e for e in pending if all(r in nums or r not in keys for r in refs(e['body']))]
    if not ready: print('CYCLE',[e['key'] for e in pending]); sys.exit(1)
    for e in ready:
        miss=[r for r in refs(e['body']) if r not in nums]
        if miss: print('UNKNOWN REF',e['key'],miss); sys.exit(1)
        payload={'title':e['title'],'body':sub(e['body']),'labels':e['labels']}
        out=subprocess.run(['gh','api','repos/s8lap/bezel-lang/issues','--method','POST','--input','-'],input=json.dumps(payload),capture_output=True,text=True)
        if out.returncode: print('FAIL',e['key'],out.stderr[:300]); sys.exit(1)
        nums[e['key']]=json.loads(out.stdout)['number']; json.dump(nums,open(d+'nums.json','w'),indent=1)
        print(e['key'],nums[e['key']])
    pending=[e for e in pending if e['key'] not in nums]

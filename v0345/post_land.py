import json,re,subprocess,sys
d,sha=sys.argv[1],sys.argv[2]
nums=json.load(open(d+'/nums.json'))
FOOT='\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
L=f'[{sha}](https://github.com/s8lap/bezel-lang/commit/{sha})'
def sub(t):
    t=re.sub(r'\{\{ISSUE:([^}]*)\}\}', lambda m: '#'+str(nums[m.group(1)]), t).replace('{{SHA}}',L).rstrip()
    if not t.endswith('(https://claude.ai/code)_'): t+=FOOT
    return t
def api(path,method,payload):
    r=subprocess.run(['gh','api',path,'--method',method,'--input','-'],input=json.dumps(payload),capture_output=True,text=True)
    print(path,method,'OK' if r.returncode==0 else 'FAIL '+r.stderr[:200])
for e in json.load(open(d+'/trackers.json')):
    a=e.get('action')
    if a in('comment','close'):
        body=e.get('body') or e.get('comment')
        if body: api(f"repos/s8lap/bezel-lang/issues/{e['issue']}/comments",'POST',{'body':sub(body)})
    if a=='close':
        api(f"repos/s8lap/bezel-lang/issues/{e['issue']}",'PATCH',{'state':'closed','state_reason':e.get('state_reason','completed')})
